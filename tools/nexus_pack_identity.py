#!/usr/bin/env python3
"""One NX number for all HATS editions. Increment sequence once per release.

Run --header before building, --edition <edition> --output <path> when packaging.
The checked-in release definition and generated header must travel with source.
"""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
EDITIONS=('standard-no-hoc','standard-hoc','nexus-themed-hoc')
def identity(edition=None):
    data=json.loads((ROOT/'nexus-release.json').read_text())
    n=data['sequence']
    assert type(n) is int and 0<n<=9999999
    assert data['schema']==1 and data['product']=='Nexus HATS'
    assert data['version']==f'NX{n}' and data['release_tag']==f'vNX{n}'
    assert len(data['atmosphere'].split('.'))==3 and all(x.isdigit() for x in data['atmosphere'].split('.'))
    if edition is not None:
        assert edition in EDITIONS
        data['edition']=edition
    return data
def header(data):
    return ('// Generated by tools/nexus_pack_identity.py; edit nexus-release.json.\n'
        '// SPDX-License-Identifier: GPL-2.0-only\n#pragma once\n'
        f'#define NEXUS_PACK_SEQUENCE {data["sequence"]}\n'
        f'#define NEXUS_PACK_VERSION "{data["version"]}"\n'
        f'#define NEXUS_BUILD_REVISION "Nexus-{data["version"]}"\n'
        f'#define NEXUS_FIRMWARE_BUILD_ID "NEXUS-{data["atmosphere"]}-{data["version"]}-independent-loader"\n')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--header',action='store_true');p.add_argument('--check',action='store_true');p.add_argument('--edition',choices=EDITIONS);p.add_argument('--output',type=Path);a=p.parse_args()
    data=identity(a.edition)
    if a.header:
        target=ROOT/'libraries/libvapours/include/vapours/nexus_version.h';text=header(data)
        if a.check:assert target.read_text()==text,'Regenerate the Nexus version header before building'
        else:target.write_text(text)
    if a.output:
        assert a.edition,'An edition is required for pack identities'
        a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text(json.dumps(data,indent=2)+'\n')
